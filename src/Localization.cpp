const std::unordered_map<std::string_view, const char*>& TranslationMap() {
    // Function-local static: safe to call from static initialisers (the category name arrays),
    // because it is built on first use.
    static const std::unordered_map<std::string_view, const char*> map = [] {
        std::unordered_map<std::string_view, const char*> result;
        result.reserve(sizeof(kTranslations) / sizeof(kTranslations[0]));
        for (const TranslationEntry& entry : kTranslations) {
            result.emplace(entry.english, entry.chinese);
        }
        return result;
    }();
    return map;
}

