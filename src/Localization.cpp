std::string_view RestLocalization::TranslateView(std::string_view english) {
#if REST_LOCALIZED_UI
    const std::unordered_map<std::string_view, const char*>& map = TranslationMap();
    const auto it = map.find(english);
    if (it != map.end()) {
        return std::string_view(it->second);
    }
#endif
    return english;
}

const char* RestLocalization::Translate(const char* english) {
    if (english == nullptr) {
        return nullptr;
    }
    // TranslateView returns the input view when there is no entry; in that case keep the caller's
    // pointer so the English build and untranslated strings are completely unaffected.
    const std::string_view translated = TranslateView(std::string_view(english));
    return translated.data() == english ? english : translated.data();
}

std::string TrLabel(const char* label) {
    if (label == nullptr) {
        return std::string();
    }

    const char* const id = std::strstr(label, "##");
    if (id == nullptr) {
        return std::string(Tr(label));
    }

    // Keep the ImGui identifier ("##...") that follows the visible part of the label.
    const std::string visible(label, static_cast<size_t>(id - label));
    return std::string(Tr(visible.c_str())) + id;
}
